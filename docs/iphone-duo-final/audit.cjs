const pick = (arg, all) => (arg ? arg.split(',').filter(Boolean) : all);

async function measure(page) {
  return page.evaluate(({ BOOK_MQ, SPINE }) => {
    const vw = document.documentElement.clientWidth;
    const vh = window.innerHeight;
    const book = matchMedia(BOOK_MQ).matches;
    const cx = vw / 2, z0 = cx - SPINE / 2, z1 = cx + SPINE / 2;
    const vis = (el) => {
      if (!el.isConnected) return false;
      if (el.checkVisibility && !el.checkVisibility({ opacityProperty: true, visibilityProperty: true })) return false;
      const r = el.getBoundingClientRect();
      return r.width > 0 && r.height > 0;
    };
    const desc = (el) => {
      const t = (el.getAttribute('aria-label') || el.placeholder || el.innerText || el.value || '').trim().replace(/\s+/g, ' ').slice(0, 40);
      const c = (typeof el.className === 'string' ? el.className : '').split(' ').filter((x) => x.startsWith('tebyan') || x.startsWith('tbn')).slice(0, 2).join('.');
      return `${el.tagName.toLowerCase()}${c ? '.' + c : ''}${t ? ` "${t}"` : ''}`;
    };
    const inHScroller = (el) => {
      for (let p = el.parentElement; p && p !== document.body; p = p.parentElement) {
        const cs = getComputedStyle(p);
        if (/(auto|scroll)/.test(cs.overflowX) && p.scrollWidth > p.clientWidth + 1) return true;
        if (/(hidden|clip)/.test(cs.overflowX) && p.tagName !== 'MAIN' && p.tagName !== 'BODY' && p.tagName !== 'HTML') {
          const pr = p.getBoundingClientRect();
          const r = el.getBoundingClientRect();
          if (r.right > pr.right + 1 || r.left < pr.left - 1) return true; // deliberately clipped (marquee, carousel)
        }
      }
      return false;
    };
    const main = document.querySelector('main');
    const overflow = {
      doc: document.documentElement.scrollWidth - document.documentElement.clientWidth,
      main: main ? main.scrollWidth - main.clientWidth : 0,
    };
    const INTER = 'a[href], button, input:not([type=hidden]), textarea, select, summary, [role=button], [role=tab], [role=link]';
    const clipped = [];
    const small = [];
    const spine = [];
    for (const el of document.querySelectorAll(INTER + ', h1, h2, h3')) {
      if (!vis(el)) continue;
      const r = el.getBoundingClientRect();
      if ((r.right > vw + 1 || r.left < -1) && !inHScroller(el)) clipped.push(desc(el) + ` [${Math.round(r.left)}..${Math.round(r.right)}]`);
      if (el.matches(INTER) && r.bottom > 0 && r.top < vh && r.left < vw && r.right > 0) {
        if ((r.width < 43.5 || r.height < 43.5) && !el.closest('.tebyan-tap-exempt') && !(el.tagName === 'A' && getComputedStyle(el).display === 'inline'))
          small.push(desc(el) + ` ${Math.round(r.width)}x${Math.round(r.height)}`);
      }
    }
    if (book) {
      // the part of a box actually painted: clipped by every scrolling/clipping ancestor
      const clipCache = new Map();
      const clipOf = (el) => {
        if (clipCache.has(el)) return clipCache.get(el);
        let c = { left: -1e9, right: 1e9, top: -1e9, bottom: 1e9 };
        for (let p = el.parentElement; p && p !== document.documentElement; p = p.parentElement) {
          const cs = getComputedStyle(p);
          if (cs.overflowX !== 'visible' || cs.overflowY !== 'visible') {
            const pr = p.getBoundingClientRect();
            c = { left: Math.max(c.left, pr.left), right: Math.min(c.right, pr.right), top: Math.max(c.top, pr.top), bottom: Math.min(c.bottom, pr.bottom) };
          }
          if (cs.position === 'fixed') break;
        }
        clipCache.set(el, c);
        return c;
      };
      const paint = (r, el) => { const c = clipOf(el); return { left: Math.max(r.left, c.left), right: Math.min(r.right, c.right), top: Math.max(r.top, c.top), bottom: Math.min(r.bottom, c.bottom) }; };
      const hitIn = (r, el) => { const p = paint(r, el); return p.right - p.left > 0.5 && p.bottom - p.top > 0.5 && p.right > z0 && p.left < z1; };
      const seen = new Set();
      for (const el of document.querySelectorAll(INTER)) {
        if (!vis(el)) continue;
        if (hitIn(el.getBoundingClientRect(), el)) { seen.add(el); spine.push('control ' + desc(el)); }
      }
      const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
      const range = document.createRange();
      for (let n = walker.nextNode(); n; n = walker.nextNode()) {
        if (!n.nodeValue.trim()) continue;
        const el = n.parentElement;
        if (!el || seen.has(el.closest(INTER)) || !vis(el) || el.closest('[aria-hidden=true], script, style, noscript')) continue;
        range.selectNodeContents(n);
        for (const r of range.getClientRects()) {
          if (hitIn(r, el)) { spine.push('text ' + desc(el) + ` "${n.nodeValue.trim().slice(0, 30)}"`); break; }
        }
      }
    }
    return { book, overflow, clipped: [...new Set(clipped)], small: [...new Set(small)], spine: [...new Set(spine)] };
  }, { BOOK_MQ, SPINE });
}

async function runStep(page, s) {
  if (s.wait) await page.waitForTimeout(s.wait);
  if (s.waitFor) await page.locator(s.waitFor).first().waitFor({ state: 'visible', timeout: 20000 });
  if (s.fill) { const l = page.locator(s.fill).first(); await l.fill(s.text, { timeout: 4000 }); await page.waitForTimeout(400); }
  if (s.click) await page.locator(s.click).first().click({ timeout: 4000 });
  if (s.clickText) await page.getByText(s.clickText, { exact: false }).first().click({ timeout: 4000 });
  if (s.key) await page.keyboard.press(s.key);
  if (s.event) await page.evaluate((e) => window.dispatchEvent(new Event(e)), s.event);
}

module.exports = { SCREENS, POSES, MAIN, BOOK_MQ, measure, runStep };

if (require.main === module) (async () => {
  const poses = pick(POSES_ARG, Object.keys(POSES));
  const screens = SCREENS.filter((s) => pick(SCREENS_ARG, SCREENS.map((x) => x.id)).includes(s.id));
  const browser = await webkit.launch();
  const results = [];
  for (const pose of poses) {
    for (const [w, h, scope] of POSES[pose]) {
      for (const demo of [true, false]) {
        // demo=false screens run as a signed-out visitor; slowChunk screens need a cold cache
        const list = screens.filter((s) => (s.demo === false) === !demo && !s.slowChunk && (scope === 'all' || MAIN.includes(s.id)));
        if (!list.length) continue;
        const ctx = await browser.newContext({ viewport: { width: w, height: h }, deviceScaleFactor: 1, isMobile: true, hasTouch: true, locale: 'ar', reducedMotion: 'reduce' });
        await ctx.addInitScript(() => { try { sessionStorage.setItem('tebyan_splash_seen', 'true'); localStorage.setItem('tebyan_onboarding_seen_v3', 'true'); localStorage.setItem('tebyan_onboarding_seen_v3_guest', 'true'); } catch {} });
        const page = await ctx.newPage();
        const errors = [];
        page.on('pageerror', (e) => errors.push(String(e.message).slice(0, 160)));
        if (demo) { await page.goto(BASE + '/?demo=1', { waitUntil: 'load' }); await page.waitForTimeout(800); }
        for (const s of list) {
          const rec = { pose, vp: `${w}x${h}`, screen: s.id };
          errors.length = 0;
          try {
            if (s.slowChunk) await page.route((u) => s.slowChunk.test(u.href), async (r) => { await new Promise((ok) => setTimeout(ok, 6000)); await r.continue().catch(() => {}); });
            if (s.offline) await ctx.setOffline(true);
            await page.goto(BASE + s.url, { waitUntil: s.offline ? 'commit' : 'load' }).catch(() => {});
            await page.waitForTimeout(s.shotEarly ? 1500 : 2000);
            for (const st of s.steps || []) await runStep(page, st);
            Object.assign(rec, await measure(page));
            if (SHOTS) await page.screenshot({ path: path.join(SHOTS, `${s.id}-${w}x${h}.jpg`), type: 'jpeg', quality: 55 });
          } catch (e) {
            rec.error = String(e.message).split('\n')[0].slice(0, 200);
          } finally {
            if (s.slowChunk) await page.unroute(() => true).catch(() => {});
            if (s.offline) await ctx.setOffline(false);
          }
          rec.pageErrors = [...errors];
          results.push(rec);
          const bad = (rec.overflow && (rec.overflow.doc > 1 || rec.overflow.main > 1)) || rec.clipped?.length || rec.spine?.length || rec.error;
          process.stdout.write(`${bad ? 'x' : '.'}`);
        }
        await ctx.close();
      }
      // loading state: a fresh context so the tab's chunk is not cached yet, delayed 6s
      for (const s of screens.filter((x) => x.slowChunk && (scope === 'all' || MAIN.includes(x.id)))) {
        // serviceWorkers: 'block' — the app's worker would otherwise serve the chunk from its cache
        const ctx = await browser.newContext({ viewport: { width: w, height: h }, deviceScaleFactor: 1, isMobile: true, hasTouch: true, locale: 'ar', reducedMotion: 'reduce', serviceWorkers: 'block' });
        await ctx.addInitScript(() => { try { sessionStorage.setItem('tebyan_splash_seen', 'true'); localStorage.setItem('tebyan_onboarding_seen_v3', 'true'); localStorage.setItem('tebyan_onboarding_seen_v3_guest', 'true'); } catch {} });
        const page = await ctx.newPage();
        const rec = { pose, vp: `${w}x${h}`, screen: s.id };
        try {
          await page.route((u) => s.slowChunk.test(u.href), async (r) => { await new Promise((ok) => setTimeout(ok, 6000)); await r.continue().catch(() => {}); });
          await page.goto(BASE + '/?demo=1', { waitUntil: 'load' });
          await page.waitForTimeout(600);
          await page.goto(BASE + s.url, { waitUntil: 'commit' });
          await page.locator('[role=status][aria-label="جارٍ التحميل"]').first().waitFor({ timeout: 5000 }).catch(() => {});
          await page.waitForTimeout(300);
          rec.skeleton = await page.evaluate(() => !!document.querySelector('[role=status][aria-label="جارٍ التحميل"]'));
          Object.assign(rec, await measure(page));
          if (SHOTS) await page.screenshot({ path: path.join(SHOTS, `${s.id}-${w}x${h}.jpg`), type: 'jpeg', quality: 55 });
        } catch (e) { rec.error = String(e.message).split('\n')[0].slice(0, 200); }
        results.push(rec);
        await ctx.close();
        process.stdout.write('l');
      }
    }
  }
  await browser.close();
  fs.writeFileSync(OUT, JSON.stringify(results, null, 1));
  const sum = { cases: results.length, overflow: 0, clipped: 0, spine: 0, small: 0, errors: 0 };
  for (const r of results) {
    if (r.overflow && (r.overflow.doc > 1 || r.overflow.main > 1)) sum.overflow++;
    if (r.clipped?.length) sum.clipped++;
    if (r.spine?.length) sum.spine++;
    if (r.small?.length) sum.small++;
    if (r.error) sum.errors++;
  }
  console.log('\n' + JSON.stringify(sum));
})();
